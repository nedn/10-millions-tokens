"""One hundred independently shuffled, unambiguous destination encodings.

Each renderer works for every label from 1 through 100. No eval, external
facts, ambiguous rounding, or dependence on the current file is required.
"""


def representations(n, english, roman):
    if not 1 <= n <= 100:
        raise ValueError('Destination must be between 1 and 100.')
    digits = 'zero one two three four five six seven eight nine'.split()
    forms = [
        str(n), english(n), roman(n) + ' in Roman notation',
        roman(n).lower() + ' in lowercase Roman notation',
        f'{n:03d} with leading zeroes ignored',
        'the decimal digits ' + ' '.join(digits[int(c)] for c in str(n)),
        f'binary {n:b}', f'octal {n:o}', f'hexadecimal {n:X}',
        f'{n:07b} interpreted in base two',
        f'{n:03o} interpreted in base eight',
        f'{n:02x} interpreted in base sixteen',
        f'{n // 10} tens plus {n % 10} ones',
        f'{n // 5} groups of five and {n % 5} extra units',
        f'{n // 12} dozens plus {n % 12}',
        f'{n * 10} divided by ten', f'one percent of {n * 100}',
        f'ten percent of {n * 10}', f'half of {n * 2}',
        f'a quarter of {n * 4}', f'a fifth of {n * 5}',
        f'a third of {n * 3}', f'three quarters of the fraction {n*4}/3',
        f'the positive square root of {n*n}',
        f'the real cube root of {n**3}',
        f'the nonnegative fourth root of {n**4}',
        f'the absolute value of negative {n}',
        f'the additive inverse of minus {n}',
        f'the successor of {n-1}', f'the predecessor of {n+1}',
        f'two greater than {n-2}', f'three less than {n+3}',
        f'the sum of {n-7} and seven',
        f'the difference between {n+11} and eleven',
        f'the product of {n} and one',
        f'the quotient of {n*7} by seven',
        f'the remainder when {n+101} is divided by 101',
        f'the mean of {n-4} and {n+4}',
        f'the median of {n+9}, {n}, and {n-9}',
        f'the maximum of {n-1} and {n}',
        f'the minimum of {n} and {n+1}',
        f'the greatest common divisor of {n*2} and {n*3}',
        f'the least common multiple of one and {n}',
        f'the floor of {n}.75', f'the ceiling of {n-1}.25',
        f'{n}.01 rounded to the nearest integer',
        f'the integer part of {n}.99',
        f'the number of integers from 1 through {n}, inclusive',
        f'the count of even integers from 2 through {n*2}, inclusive',
        f'the count of odd positive integers below {n*2}',
        f'the length of an inclusive interval of integers from 8 to {n+7}',
        f'the distance from zero to {n} on the number line',
        f'the distance between {n+6} and six',
        f'the midpoint between zero and {n*2}',
        f'the arithmetic mean of {n-1}, {n}, and {n+1}',
        f'the value of x satisfying x + 5 = {n+5}',
        f'the solution of 2x = {n*2}',
        f'the positive solution of x squared = {n*n}',
        f'the value of y in y - 9 = {n-9}',
        f'the value of z in z / 4 = {n}/4',
        f'{n+20} minus twenty', f'{n-20} plus twenty',
        f'({n+3} + {n-3}) / 2',
        f'({n*2+1} - 1) / 2',
        f'({n-1} * 2 + 2) / 2',
        f'{n*9} / (3 * 3)',
        f'{n+16} - 2 to the fourth power',
        f'{n-8} + 2 cubed',
        f'{n+25} - 5 squared',
        f'({n} squared + {n}) / {n+1}',
        f'the sum of the first {n} copies of one',
        f'the count of integers from zero through {n-1}, inclusive',
        f'the number of pairs in {n*2} objects',
        f'the number of trios in {n*3} objects',
        f'the number of weeks in {n*7} days',
        f'the number of hours in {n*60} minutes',
        f'the number of minutes in {n*60} seconds',
        f'the number of centimeters in {n*10} millimeters',
        f'the number of meters in {n*100} centimeters',
        f'the number of kilometers in {n*1000} meters',
        f'the number of grams in {n*1000} milligrams',
        f'the number of kilograms in {n*1000} grams',
        f'the number of full rotations in {n*360} degrees',
        f'the number of right angles in {n*90} degrees',
        f'the number of triangles having {n*3} sides in total',
        f'the number of squares having {n*4} sides in total',
        f'the number of hexagons having {n*6} sides in total',
        f'the number of eight-bit bytes in {n*8} bits',
        f'the number of ten-item bundles in {n*10} items',
        f'the number of dozen-item boxes in {n*12} items',
        f'the sum of {n//2} and {n-n//2}',
        f'the difference {n+1000} minus 1000',
        f'{n*100}/100 reduced to an integer',
        f'{n*11} divided by eleven',
        f'twice {n} minus {n}',
        f'three times {n} less twice {n}',
        f'the number immediately between {n-1} and {n+1}',
        f'the smaller integer in the pair ({n}, {n+10})',
        f'the larger integer in the pair ({n-10}, {n})',
        f'the unique integer strictly between {n-1}.5 and {n}.5',
    ]
    assert len(forms) == 100
    return forms
